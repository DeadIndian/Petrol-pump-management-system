"""Download and localize the reference's public design assets, including fonts."""
import concurrent.futures
import hashlib
import json
import re
import sys
from pathlib import Path
from urllib.parse import urljoin, urlparse
import requests
from bs4 import BeautifulSoup

PROJECT=Path(__file__).resolve().parents[2]
CAPTURES=Path(sys.argv[1] if len(sys.argv)>1 else "/tmp/petrosoft-reference")
ROOT=PROJECT/"public/petrosoft-assets"
ORIGIN="https://petrosoft.ymtsindia.in"
ROOT.mkdir(parents=True,exist_ok=True)

def local_path(url):
    parsed=urlparse(url)
    if parsed.netloc=="petrosoft.ymtsindia.in":return ROOT/parsed.path.lstrip("/")
    extension=".css" if parsed.netloc=="fonts.googleapis.com" else Path(parsed.path).suffix or ".asset"
    return ROOT/"external"/(hashlib.sha256(url.encode()).hexdigest()[:24]+extension)

def local_url(url):return "/petrosoft-assets/"+str(local_path(url).relative_to(ROOT))

urls=set()
for file in list(CAPTURES.glob("*.source.html"))+[CAPTURES/"reference-code.html",CAPTURES/"login.html"]:
    soup=BeautifulSoup(file.read_text(),"lxml")
    for el in soup.select("link[rel=stylesheet],img[src]"):
        url=el.get("href") or el.get("src") or ""
        if url.startswith("http"):urls.add(url)
    for style in soup.select("style"):
        urls.update(re.findall(r"https?://[^\s'\"()<>]+",style.string or "".join(str(child) for child in style.contents)))
for file in (PROJECT/"lib/petrosoft/templates").glob("*.html"):
    soup=BeautifulSoup(file.read_text(),"lxml")
    for el in soup.select("script[src]"):
        src=el["src"]
        if src.startswith("/petrosoft-assets/assets/"):urls.add(ORIGIN+"/"+src.removeprefix("/petrosoft-assets/"))
# Common icons are also generated by local table and dashboard controllers.
for image in ["navbg.png","edit.png","delete.png","loading.gif","loading11.gif","sad.png","fuel.png","oiler.png","swipe.png","profits.png","expense.png","cash-back.png","recover.png","gas2.png","default_avatar.png","yongminds-logo.png"]:
    urls.add(ORIGIN+"/assets/images/"+image)
for image in ["add.png","remove.png"]:urls.add(ORIGIN+"/assets/img/"+image)

visited=set();manifest=[];failed=[]
cached={x["source"]:x for x in json.loads((ROOT/"provenance.json").read_text())} if (ROOT/"provenance.json").exists() else {}
def fetch(url):
    if not url.startswith("http") or urlparse(url).netloc not in ["petrosoft.ymtsindia.in","fonts.googleapis.com","fonts.gstatic.com","cdnjs.cloudflare.com"]:return None
    target=local_path(url)
    if url in cached and target.exists():return {**cached[url],"additional":[]}
    try:
        response=requests.get(url,timeout=25,headers={"User-Agent":"Mozilla/5.0 AppleWebKit/537.36 Chrome/130.0.0.0 Safari/537.36"})
        response.raise_for_status()
        target.parent.mkdir(parents=True,exist_ok=True)
        additional=[]
        if target.suffix==".css":
            css=response.text
            def replace(match):
                value=match.group(1).strip(" '\"")
                if value.startswith("data:"):return match.group(0)
                resource=urljoin(url,value)
                additional.append(resource)
                return 'url("'+local_url(resource)+'")'
            css=re.sub(r"url\(([^)]+)\)",replace,css)
            target.write_text(css)
        else:target.write_bytes(response.content)
        return {"source":url,"path":str(target.relative_to(PROJECT)),"bytes":target.stat().st_size,"additional":additional}
    except Exception as error:return {"source":url,"error":str(error).split("(Caused")[0]}

with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
    while urls:
        batch=urls-visited
        if not batch:break
        visited.update(batch);urls=set()
        for result in pool.map(fetch,sorted(batch)):
            if not result:continue
            if "error" in result:failed.append(result);continue
            urls.update(result.pop("additional"));manifest.append(result)
        print(json.dumps({"downloaded":len(manifest),"remaining":len(urls-visited),"failed":len(failed)}),flush=True)
(ROOT/"provenance.json").write_text(json.dumps(manifest,indent=2))
(PROJECT/".petrosoft/asset-errors.json").write_text(json.dumps(failed,indent=2))
print(json.dumps({"assets":len(manifest),"bytes":sum(x["bytes"] for x in manifest),"failed":failed}))
